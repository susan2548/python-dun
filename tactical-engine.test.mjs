import assert from 'node:assert/strict';
import {SKILLS,POTION_HP,POTION_MP,ensureTactics,addStatus,tickDots,expireActionStatuses,advanceCooldowns,consumeFocus,accuracy,chance,statusChance,heroDamage,enemyDamage} from './tactical-engine.js';
import {GOODS,quote,purchase} from './economy.js';
const b=ensureTactics({level:0,rng:42,poison:2,poisonDamage:4,web:1});
assert.equal(b.heroStatuses.poison.turns,2,'Old save poison migrates without disappearing');
assert.equal(b.poison,0);assert.equal(b.heroStatuses.web.turns,1);
const hits=tickDots(b.heroStatuses);assert.equal(hits[0].damage,4);assert.equal(b.heroStatuses.poison.turns,1);
tickDots(b.heroStatuses);assert(!b.heroStatuses.poison,'Poison expires after exactly two owner turns');
addStatus(b.enemyStatuses,'blind',2);assert(accuracy('wizard',b.enemyStatuses,true)<accuracy('wizard',{},true));
expireActionStatuses(b.enemyStatuses);assert.equal(b.enemyStatuses.blind.turns,1);
expireActionStatuses(b.enemyStatuses);assert(!b.enemyStatuses.blind);
b.cooldowns.double_strike=2;advanceCooldowns(b,'double_strike');assert.equal(b.cooldowns.double_strike,2);
advanceCooldowns(b);assert.equal(b.cooldowns.double_strike,1);advanceCooldowns(b);assert.equal(b.cooldowns.double_strike,0);
assert.equal(SKILLS.wizard[0].id,'fireball');assert.equal(SKILLS.wizard[0].cd,0);
assert(SKILLS.adventurer.every(s=>s.cd>0));assert(SKILLS.knight.every(s=>s.cd>0));
assert(SKILLS.wizard[0].chance>0&&SKILLS.wizard[0].chance<1);
assert.equal(statusChance(SKILLS.adventurer[0],1),0,'Skeletons cannot bleed');
assert.equal(statusChance(SKILLS.adventurer[0],4),0,'Stone cannot bleed');
assert(statusChance(SKILLS.wizard[0],4)<statusChance(SKILLS.wizard[0],0));
assert.equal(heroDamage(20,{},true),26);assert.equal(heroDamage(20,{web:{turns:1}},false),15);
addStatus(b.heroStatuses,'focused',1);assert.equal(consumeFocus(b.heroStatuses,'attack'),true);assert(!b.heroStatuses.focused);
addStatus(b.heroStatuses,'focused',1);assert.equal(consumeFocus(b.heroStatuses,'guard'),false);assert(!b.heroStatuses.focused,'Guard consumes the next-turn focus window');
addStatus(b.heroStatuses,'focused',1);consumeFocus(b.heroStatuses,'item');assert(!b.heroStatuses.focused);
assert(enemyDamage(30,{guard:{turns:1}},{})<enemyDamage(30,{},{}));
assert(enemyDamage(30,{}, {chill:{turns:1}})<enemyDamage(30,{},{}));
const rolls=Array.from({length:1000},()=>chance(b,.95));assert(rolls.some(Boolean)&&rolls.some(x=>!x),'Both hits and misses are reachable');
const restored=JSON.parse(JSON.stringify(b));assert.equal(chance(b,.5),chance(restored,.5),'Saved RNG resumes exactly');
assert.equal(POTION_HP,20);assert.equal(POTION_MP,3);
const save={gold:300,potions:0,manaPotions:0,attackBonus:0,hpBonus:0,cleared:0};
assert(purchase(save,'mana').ok);assert.equal(save.gold,282);assert.equal(save.manaPotions,1);
purchase(save,'mana');purchase(save,'mana');const gold=save.gold;
assert.equal(purchase(save,'mana').ok,false);assert.equal(save.gold,gold,'Out-of-stock purchase cannot spend currency');
save.cleared=1;assert.equal(quote(save,GOODS[1]).left,3,'Stock replenishes only on a new frontier');
save.gold=0;assert.equal(purchase(save,'potion').ok,false);assert.equal(save.potions,0);
save.gold=1000;purchase(save,'attack');assert.equal(quote(save,GOODS[2]).price,90);
purchase(save,'attack');purchase(save,'attack');assert.equal(purchase(save,'attack').ok,false);
console.log('Tactics/economy passed: migration, exact status expiry, cooldowns, RNG saves, immunities, potion values, pricing and stock limits.');
